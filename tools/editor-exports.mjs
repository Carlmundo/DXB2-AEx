// Generate ABI-transparent Steam forwarding thunks from the user's own DLL.
// The original Steam DLL is never copied into the distributable.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';

const [input,output='.scratch/editor-steam']=process.argv.slice(2);
if(!input)throw new Error('Usage: node tools/editor-exports.mjs original-steam_api.dll [output-prefix]');
const bytes=await readFile(input),pe=bytes.readUInt32LE(0x3c),optional=pe+24;
if(bytes.readUInt32LE(pe)!==0x4550||bytes.readUInt16LE(optional)!==0x10b)throw new Error('Expected a 32-bit PE DLL');
const sections=[];
for(let i=0;i<bytes.readUInt16LE(pe+6);i++) {
  const at=optional+bytes.readUInt16LE(pe+20)+i*40;
  sections.push({rva:bytes.readUInt32LE(at+12),size:bytes.readUInt32LE(at+16),raw:bytes.readUInt32LE(at+20)});
}
const offset=rva=>{
  const section=sections.find(s=>rva>=s.rva&&rva<s.rva+s.size);
  if(!section)throw new Error(`Unmapped export RVA ${rva.toString(16)}`);
  return section.raw+rva-section.rva;
};
const directory=offset(bytes.readUInt32LE(optional+96));
const firstOrdinal=bytes.readUInt32LE(directory+16),count=bytes.readUInt32LE(directory+20),named=bytes.readUInt32LE(directory+24);
const functions=offset(bytes.readUInt32LE(directory+28)),names=offset(bytes.readUInt32LE(directory+32)),ordinals=offset(bytes.readUInt32LE(directory+36));
const entries=new Map();
for(let i=0;i<count;i++)if(bytes.readUInt32LE(functions+i*4))entries.set(i,{ordinal:firstOrdinal+i,names:[]});
for(let i=0;i<named;i++) {
  const at=offset(bytes.readUInt32LE(names+i*4)),name=bytes.toString('ascii',at,bytes.indexOf(0,at));
  if(!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name))throw new Error(`Unsupported export name: ${name}`);
  entries.get(bytes.readUInt16LE(ordinals+i*2)).names.push(name);
}
const exports=[...entries.values()];
const header=[
  '// Generated by tools/editor-exports.mjs from the original Steam API DLL.',
  `static FARPROC gSteam[${exports.length}]={};`,
  `static const WORD kSteamOrdinals[]={${exports.map(e=>e.ordinal).join(',')}};`,
  `static const char* const kSteamNames[]={${exports.map(e=>e.names.length?JSON.stringify(e.names[0]):'nullptr').join(',')}};`,
  ...exports.map((e,i)=>`extern "C" __declspec(naked) void AexSteam${i}() { __asm jmp dword ptr [gSteam+${i*4}] }`),''
].join('\n');
const definition=['LIBRARY steam_api','EXPORTS',...exports.flatMap((e,i)=>e.names.length?
  e.names.map(name=>`  ${name}=AexSteam${i} @${e.ordinal}`):[`  AexSteam${i} @${e.ordinal} NONAME`]),''].join('\n');
await mkdir(path.dirname(output),{recursive:true});
await writeFile(`${output}.h`,header);await writeFile(`${output}.def`,definition);
console.log(`Generated ${exports.length} Steam exports with original names and ordinals`);
