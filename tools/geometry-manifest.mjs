// Exact-build horizontal geometry patches; excludes similarly sized objects.
import fs from 'node:fs';
import {instructions} from './native-manifest.mjs';
const config=JSON.parse(fs.readFileSync(new URL('../native/geometry-config.json',import.meta.url),'utf8'));
const fieldWidth=config.anniversaryColumns*config.anniversaryCellWidth;
const cellWidth=Math.ceil(fieldWidth/config.rivalColumns),halfCell=Math.round(cellWidth/2);
const code=instructions(fs.readFileSync(process.argv[2],'utf8'));
const patches=[],hooks=[];
function replace(va,oldValue,newValue,size=1) {
  const ins=code.find(x=>x.va===va);if(!ins)throw Error('Missing instruction '+va.toString(16));
  const old=Buffer.alloc(size),value=Buffer.alloc(size);
  if(size===1){old[0]=oldValue;value[0]=newValue;}else{old.writeUInt32LE(oldValue);value.writeUInt32LE(newValue);}
  const at=ins.bytes.indexOf(old);if(at<0||ins.bytes.indexOf(old,at+1)>=0)throw Error('Ambiguous operand '+va.toString(16));
  patches.push({rva:va-0x400000+at,before:old,after:value,asm:ins.asm});
}
const registers=['eax','ecx','edx','ebx','esp','ebp','esi','edi'];
function hook(va,kind=0) {
  const start=code.findIndex(x=>x.va===va);let size=0,items=[];
  for(let i=start;size<5;i++){const ins=code[i];if(ins.va!==va+size)throw Error('Noncontiguous hook');items.push(ins);size+=ins.bytes.length;}
  const first=items[0],reg=registers.indexOf(/(?:shl|add)\s+(\w+)/.exec(first.asm)?.[1]);
  if(reg<0||reg===4)throw Error('Unsupported coordinate register');
  const absolute=[],relative=[];
  for(const ins of items){const at=ins.va-va;
    if(ins.bytes[0]===0xe8)relative.push(at+1);
    if(ins.bytes[0]!==0xe8)for(let p=1;p+4<=ins.bytes.length;p++) {
      const address=ins.bytes.readUInt32LE(p);if(address>=0x400000&&address<0x6c0000)absolute.push(at+p);
    }
  }
  hooks.push({rva:va-0x400000,size,skip:first.bytes.length,reg,kind,absolute,relative,bytes:Buffer.concat(items.map(x=>x.bytes))});
}
for(const va of [0x45c44d,0x45d289,0x45d2fb,0x45db83,0x45eb99,0x45f0a9,0x45fde3,
  0x46054b,0x460791,0x46089c,0x48154b,0x481979,0x4846bd,0x484f34,0x485be3,
  0x4860ac,0x48651f,0x4865a8,0x4865e0,0x489631,0x48b193])hook(va);
hook(0x45fb1f,1);hook(0x4899fe,2);
// Raster cells overlap occasionally; positions round x * fieldWidth / 37.
for(const va of [0x45db86,0x46054e,0x460794,0x48199f,0x4846a3,0x485be6,0x489635])replace(va,24,halfCell);
for(const va of [0x4874e8,0x487507])replace(va,24,halfCell,4);
replace(0x48154e,19,halfCell-5);
for(const va of [0x45fe32,0x45fe73,0x484fc3,0x4853db,0x4853f4,0x481ee5])replace(va,48,cellWidth);
for(const va of [0x481c86,0x4851fd,0x48523e,0x485251,0x48b1be])replace(va,48,cellWidth,4);
// Animated powerup-crate border: its two horizontal loops and colour-wave
// centre have their own dimensions, independent of the outer clipping rect.
replace(0x489f45,47,cellWidth-1);
replace(0x489f6a,48,cellWidth);
const waveScale=Buffer.alloc(4);waveScale.writeFloatLE(cellWidth/2);
replace(0x489e9d,0x41c00000,waveScale.readUInt32LE(),4);
const borderCentre=Buffer.alloc(4);borderCentre.writeUInt32LE(0x560ddc);
patches.push({rva:0x89ebd,before:borderCentre,after:Buffer.alloc(4),halfCellAddress:true,asm:'powerup border horizontal centre'});
const f=Buffer.alloc(4);f.writeFloatLE(fieldWidth/config.rivalColumns);
const d=Buffer.alloc(8);d.writeDoubleLE(fieldWidth/config.rivalColumns);
patches.push({rva:0x160de4,before:Buffer.from('00004042','hex'),after:f,asm:'horizontal float scale'});
patches.push({rva:0x163ec8,before:Buffer.from('0000000000004840','hex'),after:d,asm:'horizontal double scale'});
const bytes=b=>'{'+[...b].join(',')+'}';
fs.writeFileSync(process.argv[3], `// Generated by tools/geometry-manifest.mjs\ninline constexpr int kRivalFieldWidth=${fieldWidth}, kRivalRasterWidth=${cellWidth}, kRivalColumns=${config.rivalColumns};\ninline const float kRivalHalfCell=${(cellWidth/2).toFixed(1)}f;\nstatic const GeometryPatch kGeometryPatches[] = {\n`+patches.map(p=>
  `  {0x${p.rva.toString(16)}, ${p.before.length}, ${bytes(p.before)}, ${bytes(p.after)}, ${p.halfCellAddress?'true':'false'}}, // ${p.asm}`).join('\n')+'\n};\n'+
  'static const CoordinateHook kCoordinateHooks[] = {\n'+hooks.map(h=>
  `  {0x${h.rva.toString(16)},${h.size},${h.skip},${h.reg},${h.kind},${bytes(h.bytes)},${h.absolute[0]??-1},${h.relative[0]??-1}},`).join('\n')+'\n};\n');
console.log(`Wrote ${patches.length} geometry operands and ${hooks.length} coordinate hooks`);
