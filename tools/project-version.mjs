// Generate the native version string from the project's package metadata.
import fs from 'node:fs';
import path from 'node:path';

const {version}=JSON.parse(fs.readFileSync(new URL('../package.json',import.meta.url),'utf8'));
if(typeof version!=='string'||!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(version))
  throw new Error('package.json must contain a valid project version');
const output=process.argv[2];
if(!output)throw new Error('Usage: node tools/project-version.mjs output-header');
fs.mkdirSync(path.dirname(output),{recursive:true});
fs.writeFileSync(output,`// Generated by tools/project-version.mjs from package.json.\n#pragma once\n#define AEX_VERSION_WIDE L"${version}"\n`);
console.log(`Generated AEx version ${version}`);
